// Builds docs/melika/ from docs/index.html: the same app with Melika's settings, its own link, storage key,
// home-screen name and service worker. One source of code: fix docs/index.html, then rebuild.
// Run after every change to docs/index.html:  node tools/build_melika.mjs
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const DOCS = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs');
const OUT = join(DOCS, 'melika');
mkdirSync(OUT, {recursive: true});
function swap(text, from, to, file) {
  if (!text.includes(from)) throw new Error(`${file}: "${from.slice(0, 80)}" not found`);
  return text.split(from).join(to);
}
const SERVICES = [ // minutes are a first guess; corrected after a month of real bookings
  ['kasht', 'کاشت', 120, 950000], ['tarmim', 'ترمیم', 90, 750000], ['laminet', 'لمینت', 60, 750000],
  ['gelish', 'ژلیش', 45, 500000], ['remove', 'ریموو', 20, 200000], ['mani', 'مانیکور', 30, 300000]];

// ---- index.html
let html = readFileSync(join(DOCS, 'index.html'), 'utf8');
const svcBlock = html.match(/const DEF_SETTINGS=\{services:\[[\s\S]*?\],/);
if (!svcBlock) throw new Error('index.html: DEF_SETTINGS not found');
html = swap(html, svcBlock[0], 'const DEF_SETTINGS={services:[\n' +
  SERVICES.map(([id, label, min, price]) => `  {id:'${id}',label:'${label}',min:${min},price:${price}}`).join(',\n') + '],', 'index.html');
html = swap(html, "const KEY='daftar-mojgan-v1';", "const KEY='daftar-melika-v1';", 'index.html');
html = swap(html, '<title>دفتر نوبت مژگان</title>', '<title>دفتر نوبت ملیکا</title>\n<meta name="apple-mobile-web-app-title" content="دفتر نوبت ملیکا">\n<meta name="apple-mobile-web-app-capable" content="yes">', 'index.html');
html = swap(html, "['mani','مانیکوریست']", "['mate','معرفی همکار']", 'index.html');
html = swap(html, 'const PILOT_ON=true;', 'const PILOT_ON=false;', 'index.html');
html = swap(html, 'const AMOUNT_PREFILL=true;', 'const AMOUNT_PREFILL=false;', 'index.html'); // the real invoice, not the price list
html = swap(html, 'مژگان هستم', 'ملیکا هستم', 'index.html');
html = swap(html, "url('fonts/", "url('../fonts/", 'index.html');
html = swap(html, 'href="icons/', 'href="../icons/', 'index.html');
html = swap(html, '<!doctype html>\n', '<!doctype html>\n<!-- generated by tools/build_melika.mjs from ../index.html; do not edit by hand -->\n', 'index.html');
if (html.includes('مژگان')) throw new Error('index.html: «مژگان» still in Melika\'s app');
writeFileSync(join(OUT, 'index.html'), html);

// ---- sw.js: own cache (changes with every build), own files, never touches the other apps' caches
let sw = readFileSync(join(DOCS, 'sw.js'), 'utf8');
const hash = createHash('sha256').update(html).digest('hex').slice(0, 8);
sw = sw.replace(/const CACHE = '[^']+';/, `const CACHE = 'daftar-melika-${hash}';`);
sw = swap(sw, "'fonts/Vazirmatn-var.woff2'", "'../fonts/Vazirmatn-var.woff2'", 'sw.js');
sw = swap(sw, "'icons/", "'../icons/", 'sw.js');
sw = swap(sw, "keys.filter(k => k !== CACHE && !k.startsWith('daftar-preview') && !k.startsWith('daftar-melika'))", "keys.filter(k => k !== CACHE && k.startsWith('daftar-melika'))", 'sw.js');
sw = swap(sw, " || url.pathname.includes('/preview/') || url.pathname.includes('/melika/')) return;", ') return;', 'sw.js');
sw = swap(sw, '  // docs/preview/ and docs/melika/ are separate apps with their own workers; never answer for them\n', '', 'sw.js');
writeFileSync(join(OUT, 'sw.js'), '// generated by tools/build_melika.mjs from ../sw.js; do not edit by hand\n' + sw);

// ---- manifest: a separate installable app
const man = JSON.parse(readFileSync(join(DOCS, 'manifest.webmanifest'), 'utf8'));
man.id = './'; man.name = 'دفتر نوبت ملیکا'; man.short_name = 'دفتر نوبت';
man.icons = man.icons.map(i => Object.assign({}, i, {src: '../' + i.src}));
writeFileSync(join(OUT, 'manifest.webmanifest'), JSON.stringify(man, null, 2) + '\n');
console.log(`docs/melika built (cache daftar-melika-${hash})`);
