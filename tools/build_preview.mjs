// Builds docs/preview/ from docs/index.html: same app, separate storage key, manifest and service worker,
// so it can be tried on a phone with synthetic data without touching the real app or its data.
// Run after every change to docs/index.html:  node tools/build_preview.mjs
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const DOCS = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs');
const OUT = join(DOCS, 'preview');
mkdirSync(OUT, {recursive: true});
function swap(text, from, to, file) {
  const n = text.split(from).length - 1;
  if (n < 1) throw new Error(`${file}: "${from}" not found`);
  return text.split(from).join(to);
}

// ---- index.html
let html = readFileSync(join(DOCS, 'index.html'), 'utf8');
html = swap(html, "const KEY='daftar-mojgan-v1';", "const KEY='daftar-preview';", 'index.html');
html = swap(html, '<title>دفتر نوبت مژگان</title>', '<title>دفتر نوبت · پیش‌نمایش</title>\n<meta name="robots" content="noindex">', 'index.html');
html = swap(html, "url('fonts/", "url('../fonts/", 'index.html');
html = swap(html, 'href="icons/', 'href="../icons/', 'index.html');
html = swap(html, '<!doctype html>\n', '<!doctype html>\n<!-- generated by tools/build_preview.mjs from ../index.html; do not edit by hand -->\n', 'index.html');
// a visible preview strip + a synthetic-list maker (every test message goes to the tester's own number)
html = swap(html, '</style>', `.pvbar{display:flex;align-items:center;justify-content:space-between;gap:8px;background:#E8A317;color:#26192A;font-size:13px;font-weight:700;padding:calc(6px + env(safe-area-inset-top,0px)) 16px 6px}
.pvbar button{height:36px;border-radius:10px;border:none;background:#26192A;color:#fff;padding:0 12px;font-weight:700}
</style>`, 'index.html');
html = swap(html, '<body>\n', `<body>
<div class="pvbar"><span>پیش‌نمایش · داده‌ی جدا از اپ مژگان</span><button id="pvCsv" type="button">فهرست ساختگی</button></div>
<script>
// preview only: a synthetic list file (60 fake people) to import from ☰ → پایلوت
document.getElementById('pvCsv').addEventListener('click', function () {
  var ph = prompt('شماره‌ی موبایل خودت؛ همه‌ی پیام‌های تست فقط به همین شماره می‌رود. (خالی = بدون شماره، برای تمرین «پیدا کردن شماره»)', '') ;
  if (ph === null) return;
  ph = ph.replace(/[۰-۹]/g, function (d) { return '۰۱۲۳۴۵۶۷۸۹'.indexOf(d) }).replace(/\\D/g, '');
  var svc = ['ترمیم', 'لاک ژل + پدیکور', 'پدیکور', 'ژل پا'], fa = function (s) { return String(s).replace(/\\d/g, function (d) { return '۰۱۲۳۴۵۶۷۸۹'[d] }) };
  var rows = ['ردیف,نام مشتری,آخرین مراجعه (شمسی),آخرین مراجعه (میلادی),تعداد مراجعه,خدمت آخر,میانگین فاکتور (تومان),شماره تلفن,منبع شماره,نوبت از پیش گرفته؟,یادداشت بازبینی'];
  for (var i = 0; i < 60; i++) {
    var d = new Date(); d.setDate(d.getDate() - (45 + (i * 7) % 46));
    var iso = d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
    rows.push([i + 1, 'تست ' + fa(String(i + 1).padStart(2, '0')), '', iso, 1 + i % 3, svc[i % 4], 400000,
      ph && i < 50 ? ph : '', ph && i < 50 ? 'گوشی' : '', '', i % 9 === 0 ? 'یادداشت بازبینی ساختگی' : ''].join(','));
  }
  var a = document.createElement('a');
  a.href = URL.createObjectURL(new Blob(['\\ufeff' + rows.join('\\n')], {type: 'text/csv'}));
  a.download = 'pilot-test-list.csv'; document.body.appendChild(a); a.click();
  setTimeout(function () { URL.revokeObjectURL(a.href); a.remove() }, 1500);
});
</script>
`, 'index.html');
writeFileSync(join(OUT, 'index.html'), html);

// ---- sw.js: own cache name (changes with every build), own file list, never touches the real app's cache
let sw = readFileSync(join(DOCS, 'sw.js'), 'utf8');
const hash = createHash('sha256').update(html).digest('hex').slice(0, 8);
sw = sw.replace(/const CACHE = '[^']+';/, `const CACHE = 'daftar-preview-${hash}';`);
sw = swap(sw, "'fonts/Vazirmatn-var.woff2'", "'../fonts/Vazirmatn-var.woff2'", 'sw.js');
sw = swap(sw, "'icons/", "'../icons/", 'sw.js');
sw = swap(sw, "keys.filter(k => k !== CACHE && !k.startsWith('daftar-preview') && !k.startsWith('daftar-melika'))", "keys.filter(k => k !== CACHE && k.startsWith('daftar-preview'))", 'sw.js');
sw = swap(sw, " || url.pathname.includes('/preview/') || url.pathname.includes('/melika/')) return;", ') return;', 'sw.js');
sw = swap(sw, '  // docs/preview/ and docs/melika/ are separate apps with their own workers; never answer for them\n', '', 'sw.js');
writeFileSync(join(OUT, 'sw.js'), '// generated by tools/build_preview.mjs from ../sw.js; do not edit by hand\n' + sw);

// ---- manifest: a separate installable app
const man = JSON.parse(readFileSync(join(DOCS, 'manifest.webmanifest'), 'utf8'));
man.id = './'; man.name = 'دفتر نوبت · پیش‌نمایش'; man.short_name = 'پیش‌نمایش';
man.icons = man.icons.map(i => Object.assign({}, i, {src: '../' + i.src}));
writeFileSync(join(OUT, 'manifest.webmanifest'), JSON.stringify(man, null, 2) + '\n');
console.log(`docs/preview built (cache daftar-preview-${hash})`);
